"""Initialising a Quarrix output folder (often a private Git repository)."""

from __future__ import annotations

from pathlib import Path

README = """# Documents extracted with Quarrix

PDF documents extracted with [Quarrix](https://github.com/samagior/Quarrix),
with their heading hierarchy, tables and figures.

- `sources/<doc>/`: full extraction. **Internal use** when the documents are
  protected by copyright: keep this folder private.
- `sources/<doc>/meta.json`: provenance, licence and classification. Fill it in
  for each document.
- `sources/<doc>/derived/`: derived content, written in our own words (values,
  formulas, parameters, summaries), with section/page references. This is what
  may be distributed.
- `types.toml`: document types (with their Docling configuration), categories
  and suggested subjects. Edit by hand or with "Manage types…".
- `index.json`: catalog generated automatically, with the classification of each
  document (category, author, type, subjects) and facets for filtering.
- `dist/`: distributable pack generated by `quarrix dist` (ignored by Git). With
  `--publish-dir`, it is copied elsewhere (for example to a public repository).

Before each distribution, check `licence.status`, `licence.distribution`,
`exclude`, `redact` and `share.tables` in every `meta.json`.
"""

CLAUDE_MD = """# Documents extracted with Quarrix: notes for Claude

Reference documents extracted from PDFs by Quarrix, keeping the original
hierarchy.

## Finding information

1. `index.json`: filter by `classification` (`type`, `subjects`, `author`,
   `category`) or with `facets`.
2. `sources/<id>/document.json` → `outline` to locate the section.
3. `sources/<id>/document.md` to read; `tables/*.csv` for exact values.
4. Cite the source as `<id>#<section>` or `<id>#<table>` (e.g.
   `guide-…#4.2.1`, `…#t012`), in code as well as in `derived/`.

## Writing derived content (`sources/<id>/derived/`)

This is the only part distributed when the source is protected. Rules:

- Never copy the text, figures or layout of the source: rephrase, structure,
  cite section and page.
- `parameters.json`: values and parameters, each with `value`, `unit`,
  `source` (`doc`, `section`, `page`, `table`).
- `formulas.md`: formulas with our own notation, variables and units.
- `summary.md`: summary in our own words, not a line-by-line paraphrase.
- Do not edit `sources/<id>/document.*`, `tables/`, `figures/` by hand: they
  are regenerated by extraction. `meta.json` is edited by hand.

## Before distributing

Check in every `meta.json`: `licence.status`, `licence.distribution`,
`exclude`, `redact`, `share.tables`, then run `quarrix dist` and review `NOTICE.md`.
"""

GITIGNORE = """dist/
# raw Docling export (only with native_export = true): large, kept locally
native.json
native.json.gz
*.pdf
.DS_Store
Thumbs.db
"""

GITATTRIBUTES = """*.png filter=lfs diff=lfs merge=lfs -text
*.jpg filter=lfs diff=lfs merge=lfs -text
"""

DERIVED_README = """# Derived content

Files written from the source, without copying its text:

- `parameters.json`: structured values and parameters, each with a `source`
  (`{"section": "4.2", "page": 37, "table": "t003"}`).
- `formulas.md`: rephrased formulas, defined variables, units.
- `summary.md`: summary in our own words.
"""


def init_data_repo(root: Path, lfs: bool = False) -> list[Path]:
    """Create the base structure without overwriting existing files."""
    root.mkdir(parents=True, exist_ok=True)
    (root / "sources").mkdir(exist_ok=True)
    created = []
    files = {
        "README.md": README,
        ".gitignore": GITIGNORE,
        "sources/_derived_template/README.md": DERIVED_README,
        "CLAUDE.md": CLAUDE_MD,
    }
    if lfs:
        files[".gitattributes"] = GITATTRIBUTES
    for rel, content in files.items():
        p = root / rel
        if p.exists():
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
        created.append(p)
    return created
